CONTEXTS = tuple(_Q1)
_rng = random.Random()
_recent: dict[str, deque[str]] = defaultdict(lambda: deque(maxlen=40))


def pick(ctx: str, level: int = 1, seed: int | None = None) -> str:
    """Случайная фраза для ситуации.

    seed — чтобы при перерисовке одного и того же сообщения фраза не менялась.
    """
    base = _Q1.get(ctx) or _Q1["general"]
    hard = _Q2.get(ctx, []) if level >= 2 else []
    rnd = random.Random(seed) if seed is not None else _rng
    pool = hard if hard and rnd.random() < 0.6 else base
    if seed is not None:
        return rnd.choice(pool)
    recent = _recent[ctx]
    fresh = [q for q in pool if q not in recent]  # недавние фразы не повторяем
    choice = rnd.choice(fresh or pool)
    recent.append(choice)
    return choice


def quote(ctx: str, level: int = 1, seed: int | None = None) -> str:
    """Фраза, оформленная цитатой для HTML-сообщения."""
    return f"<blockquote>🔥 {html.escape(pick(ctx, level, seed), quote=False)}</blockquote>"
